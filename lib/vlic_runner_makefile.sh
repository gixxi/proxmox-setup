# shellcheck shell=bash
# vlic_runner_makefile.sh — single source of the vlic_runner Makefile.
#
# Sourced by
#   3_vm_provissioning/create_makefile.sh             Proxmox app VM (deployed via scp, app port on the VM IP for the bastion)
#   public_cloud_vm_provisioning/2_create_makefile.sh single public Docker host (app port on loopback, local nginx)
#
# Security model (rocklog-vlic: doc/security/incident-2026-10-15-hub16.md, doc/security/host_firewall.md)
#   app      container 8080 -> APP_BIND:VLIC_PORT       only address the reverse proxy needs
#   nREPL    container 4050 -> 127.0.0.1:1VLIC_PORT      unauthenticated code execution -> never on the network
#   CouchDB  container 5984 -> 127.0.0.1:2VLIC_PORT      1.x admin party = code execution -> never on the network
#   Remote admin access goes through an SSH tunnel, e.g. ssh -L 18085:127.0.0.1:18085 <host>
#   The CircleCI key lives in .circleci_apikey (mode 600) next to the Makefile, never inside it.

# render_vlic_runner_makefile [CORES=n] [SWAP_HEADROOM_GB=n] [APP_BIND=ipv4]
# Writes the Makefile to stdout. The values become defaults; each stays overridable per call
# (make 64bit CORES=6 APP_BIND=…).
render_vlic_runner_makefile() {
    local cores=4 swap=8 app_bind=127.0.0.1 kv
    for kv in "$@"; do
        case "$kv" in
            CORES=*)            cores=${kv#*=} ;;
            SWAP_HEADROOM_GB=*) swap=${kv#*=} ;;
            APP_BIND=*)         app_bind=${kv#*=} ;;
            *) echo "render_vlic_runner_makefile: unknown option '$kv'" >&2; return 2 ;;
        esac
    done
    [[ $cores =~ ^[0-9]+$ ]]    || { echo "CORES must be a number: '$cores'" >&2; return 2; }
    [[ $swap =~ ^[0-9]+$ ]]     || { echo "SWAP_HEADROOM_GB must be a number: '$swap'" >&2; return 2; }
    [[ $app_bind =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}$ ]] || { echo "APP_BIND must be an IPv4 address: '$app_bind'" >&2; return 2; }
    if [ "$app_bind" = 0.0.0.0 ]; then
        echo "WARNING: APP_BIND=0.0.0.0 publishes the app port on every interface; Docker bypasses the host firewall." >&2
    fi

    sed -e "s/@@CORES@@/$cores/" -e "s/@@SWAP_HEADROOM_GB@@/$swap/" -e "s/@@APP_BIND@@/$app_bind/" <<'MAKEFILE'
# vlic_runner Makefile — GENERATED by proxmox-setup/lib/vlic_runner_makefile.sh, do not edit; regenerate instead.
#
# Published ports (see generator header for the security model):
#   $(APP_BIND):$(VLIC_PORT)       -> app 8080        reverse-proxy target
#   $(ADMIN_BIND):1$(VLIC_PORT)    -> nREPL 4050      ssh -L 1$(VLIC_PORT):127.0.0.1:1$(VLIC_PORT) <host>
#   $(ADMIN_BIND):2$(VLIC_PORT)    -> CouchDB 5984    ssh -L 2$(VLIC_PORT):127.0.0.1:2$(VLIC_PORT) <host>

mkfile_dir := $(dir $(abspath $(lastword $(MAKEFILE_LIST))))
VERSION := v12
current_dir := $(shell pwd)

ifndef CIRCLECI_APIKEY
	CIRCLECI_APIKEY := $(shell cat $(mkfile_dir).circleci_apikey 2>/dev/null)
endif

ifndef APP_BIND
	APP_BIND := @@APP_BIND@@
endif

# Never widen without a firewall rule in DOCKER-USER: nREPL and CouchDB 1.x are code execution.
ifndef ADMIN_BIND
	ADMIN_BIND := 127.0.0.1
endif

ifndef VLIC_PORT
	VLIC_PORT := 8080
endif

ifndef COUCHDB_PORT
	COUCHDB_PORT := 5984
endif

ifndef CORES
	CORES := @@CORES@@
endif

ifndef Xmx
	Xmx := 4g
endif

# Swap headroom in GB (operand) — overridable
ifndef SWAP_HEADROOM_GB
	SWAP_HEADROOM_GB := @@SWAP_HEADROOM_GB@@
endif
ifndef HEAP_HEADROOM
	HEAP_HEADROOM := 2
endif

# Memory management parameters - will be calculated based on Xmx if not set
ifndef MEMORY_RESERVATION_GB
	MEMORY_RESERVATION_GB := 0
endif

JAVA_HEAP=$(Xmx)
HEAP_NUM=$(JAVA_HEAP:g=)

# Computed totals (note: := so they expand once, now, with HEAP_NUM known)
DOCKER_MEMORY      := $(shell echo $$(( $(HEAP_NUM) + $(HEAP_HEADROOM) )))g
SWAP_TOTAL_GB      := $(shell echo $$(( $(HEAP_NUM) + $(SWAP_HEADROOM_GB) + $(HEAP_HEADROOM) )))
DOCKER_SWAP_MEMORY := $(SWAP_TOTAL_GB)g

# Validate and calculate memory reservation
MIN_RESERVATION_GB := $(shell echo $$(( $(HEAP_NUM) + 1 )))

ifeq ($(MEMORY_RESERVATION_GB),0)
	MEMORY_RESERVATION_GB := $(shell echo $$(( $(HEAP_NUM) + 1 )))
endif

RESERVATION_CHECK := $(shell if [ $(MEMORY_RESERVATION_GB) -lt $(MIN_RESERVATION_GB) ]; then echo "ERROR"; fi)

DOCKER_MEMORY_RESERVATION := $(MEMORY_RESERVATION_GB)g
SWAP_CONFIG := --memory-swap=$(DOCKER_SWAP_MEMORY)

ifndef IMAGE
	IMAGE := gixxi/vlic_runner:$(VERSION)
endif

# CouchDB/Erlang scales fd table with RLIMIT_NOFILE; Docker defaults are huge and can cause
# multi-GB fd_tab allocations. Override if needed: make DOCKER_ULIMIT_NOFILE=262144 …
ifndef DOCKER_ULIMIT_NOFILE
	DOCKER_ULIMIT_NOFILE := 65536
endif

ifndef CONT_NAME
	CONT_NAME := $(shell date +%s | sha256sum | base64 | head -c 32)
endif

DOCKER_RUN := docker run --ulimit nofile=$(DOCKER_ULIMIT_NOFILE):$(DOCKER_ULIMIT_NOFILE) -e LANG=C.UTF-8 -e LC_ALL=C.UTF-8

persist:
	-mkdir $(CONT_NAME)
	-mkdir $(CONT_NAME)/data
	-mkdir $(CONT_NAME)/tmp
	-mkdir $(CONT_NAME)/tmp/vlic
	-mkdir $(CONT_NAME)/log
	-mkdir $(CONT_NAME)/log/evictor

extract: persist
	@test -f rocklog-vlic-$(BUILD).tar.gz || test -n "$(CIRCLECI_APIKEY)" || { echo "ERROR: rocklog-vlic-$(BUILD).tar.gz missing and no CircleCI key (put it into $(mkfile_dir).circleci_apikey, mode 600)"; exit 1; }
	@test -f rocklog-vlic-$(BUILD).tar.gz || curl -sS -H "Circle-Token: $(CIRCLECI_APIKEY)" https://circleci.com/api/v1.1/project/github/lambdaroyal/rocklog-vlic/$(BUILD)/artifacts | grep -o 'https://[^"]*' | wget --verbose --header "Circle-Token: $(CIRCLECI_APIKEY)" --input-file -
	-cp rocklog-vlic.tar.gz rocklog-vlic-$(BUILD).tar.gz
	-cp rocklog-vlic-$(BUILD).tar.gz $(CONT_NAME)/tmp/vlic/rocklog-vlic.tar.gz
	-rm rocklog-vlic.tar.gz

bash: persist
	echo "Starting bash in new container"
	$(DOCKER_RUN) --name=$(CONT_NAME) -it --restart='always' -p $(ADMIN_BIND):$(COUCHDB_PORT):5984 -p $(ADMIN_BIND):5987:5986 -p $(APP_BIND):$(VLIC_PORT):8080 -v $(current_dir)/$(CONT_NAME)/data:/data -v $(current_dir)/$(CONT_NAME)/tmp/vlic:/tmp/vlic -v $(current_dir)/$(CONT_NAME)/log ${IMAGE} bash

couchdb: persist
	echo "Starting bash in new container"
	$(DOCKER_RUN) --name=$(CONT_NAME) -it -p $(ADMIN_BIND):$(COUCHDB_PORT):5984 -p $(APP_BIND):$(VLIC_PORT):8080 -v $(current_dir)/$(CONT_NAME)/data:/data -v $(current_dir)/$(CONT_NAME)/tmp/vlic:/tmp/vlic -v $(current_dir)/$(CONT_NAME)/log ${IMAGE} couchdb bash

64bit: extract
	echo "Building container with unique data dir $(CONT_NAME) with archive $(ARCHIVE) for customer data, image=$(IMAGE) -Xmx=$(Xmx) cores=$(CORES)"
	echo "Memory config: limit=$(DOCKER_MEMORY), reservation=$(DOCKER_MEMORY_RESERVATION), swap=$(ENABLE_SWAP)"
	echo "Ports: app $(APP_BIND):$(VLIC_PORT), nREPL $(ADMIN_BIND):1$(VLIC_PORT), CouchDB $(ADMIN_BIND):2$(VLIC_PORT)"
	@if [ "$(RESERVATION_CHECK)" = "ERROR" ]; then \
		echo "ERROR: MEMORY_RESERVATION_GB ($(MEMORY_RESERVATION_GB)GB) must be at least Xmx + 1GB ($(MIN_RESERVATION_GB)GB)"; \
		echo "Current Java heap: $(HEAP_NUM)GB, minimum reservation required: $(MIN_RESERVATION_GB)GB"; \
		echo "Please set MEMORY_RESERVATION_GB=$(MIN_RESERVATION_GB) or higher"; \
		exit 1; \
	fi
	-docker rm -f $(CONT_NAME)
	$(DOCKER_RUN) --rm --name=$(CONT_NAME) \
		-p $(APP_BIND):$(VLIC_PORT):8080 -p $(ADMIN_BIND):1$(VLIC_PORT):4050 -p $(ADMIN_BIND):2$(VLIC_PORT):5984 \
		-v $(current_dir)/$(CONT_NAME)/.ssh:/.ssh \
		-v $(current_dir)/$(CONT_NAME)/data:/data \
		-v $(current_dir)/$(CONT_NAME)/tmp/vlic:/tmp/vlic \
		-v $(current_dir)/$(CONT_NAME)/log:/usr/local/var/log/couchdb/ \
		-v $(current_dir)/$(CONT_NAME)/log/evictor:/log \
		-v /etc/localtime:/etc/localtime:ro \
		--cpus="$(CORES)" --log-driver=local \
		--memory=$(DOCKER_MEMORY) --memory-reservation=$(DOCKER_MEMORY_RESERVATION) \
		$(SWAP_CONFIG) \
		$(IMAGE) couchdb 64bit $(Xmx)
MAKEFILE
}

# Shell command, run inside the vlic_runner directory (locally or via ssh), that moves a CircleCI key
# inlined by older generator versions ("CIRCLECI_APIKEY := …") into .circleci_apikey (mode 600),
# so regenerating the Makefile does not lose it. No-op if .circleci_apikey already exists.
VLIC_RUNNER_KEY_MIGRATE_CMD='[ -f .circleci_apikey ] || { k=$(sed -n "s/^CIRCLECI_APIKEY := //p" Makefile 2>/dev/null | head -1); case "$k" in ""|"<"*) ;; *) (umask 077; printf "%s\n" "$k" > .circleci_apikey) && echo "migrated inline CircleCI key to .circleci_apikey";; esac; }'

# Shell command, run inside the vlic_runner directory, that stores the key read from stdin (mode 600).
# Feed the key via stdin, never as an argument, so it does not show up in ps or shell history.
# shellcheck disable=SC2034  # used by the sourcing scripts
VLIC_RUNNER_KEY_WRITE_CMD='umask 077 && cat > .circleci_apikey'
